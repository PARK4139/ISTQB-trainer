import assert from 'node:assert/strict';
import { mkdtempSync, cpSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import vm from 'node:vm';
import { spawnSync } from 'node:child_process';
import { createStudyStore } from './study-store.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixture=mkdtempSync(path.join(tmpdir(),'ctfl-global-edit-'));
for(const name of ['scripts','web','content','notes'])cpSync(path.join(root,name),path.join(fixture,name),{recursive:true});
let store=createStudyStore(fixture),content=store.content();
const catalogue=content.catalogue();
assert.ok(catalogue.length>1000);
for(const kind of ['interface','appData','officialDataJSON','localeResourcesJSON','googleAnswersJSON','notes'])assert.ok(catalogue.some(row=>row.kind===kind),kind);
assert.ok(!catalogue.some(row=>row.id.endsWith('/id')||row.id.endsWith('/query')||row.id.endsWith('/sourceUrl')||row.id.endsWith('/correct')));
const official=catalogue.find(row=>row.kind==='officialDataJSON'&&row.id.endsWith('/prompt'));
const locale=catalogue.find(row=>row.id==='localeResourcesJSON:resources/feedback.correct');
const note=catalogue.find(row=>row.id==='notes:main');
const google=catalogue.find(row=>row.kind==='googleAnswersJSON'&&row.value.length>40);
const changes=[official,locale,note,google].map(row=>({id:row.id,value:row.value+' fixture',version:row.version}));
const saved=content.batch(changes);
assert.deepEqual(saved.exportErrors,[]);
for(const before of [official,locale,note,google])assert.equal(saved.records.find(row=>row.id===before.id).value,before.value+' fixture');
assert.equal(content.catalogue().find(row=>row.id===official.id).original,official.original);
const metadata=content.documents()['google-source'];
assert.ok(metadata.D01.sourceUrl.startsWith('https://www.google.com/'));
assert.equal(content.documents().googleAnswersJSON[JSON.parse(google.path)[0]].userModified,true);
const db=new DatabaseSync(path.join(fixture,'content','locales.sqlite'));
assert.equal(db.prepare('SELECT value FROM locale_resource WHERE resource_key = ? AND locale = ?').get('feedback.correct','ko').value,locale.value+' fixture');
db.close();
const after=content.catalogue(),current=id=>after.find(row=>row.id===id);
assert.throws(()=>content.batch([{id:official.id,value:'must roll back',version:current(official.id).version},{id:locale.id,value:'stale',version:locale.version}]),{status:409});
assert.equal(content.catalogue().find(row=>row.id===official.id).value,current(official.id).value);
assert.equal(content.history().length,1);
assert.throws(()=>content.batch([{id:locale.id,value:'bad',version:current(locale.id).version},{id:locale.id,value:'bad',version:current(locale.id).version}]),{status:400});
const versions=Object.fromEntries(content.catalogue().map(row=>[row.id,row.version]));
const restored=content.restore(saved.batchId,versions);
assert.deepEqual(restored.exportErrors,[]);
for(const before of [official,locale,note,google])assert.equal(restored.records.find(row=>row.id===before.id).value,before.value);
content.exportContent();
const export1=readFileSync(path.join(fixture,'content','study-content.json'),'utf8');
const html1=readFileSync(path.join(fixture,'web','index.html'),'utf8');
content.exportContent();
assert.equal(readFileSync(path.join(fixture,'content','study-content.json'),'utf8'),export1);
assert.equal(readFileSync(path.join(fixture,'web','index.html'),'utf8'),html1);
const currentNote=store.readNotes();store.saveNotes('notes only',currentNote.revision);
assert.equal(readFileSync(path.join(fixture,'web','index.html'),'utf8'),html1);
const updated=content.catalogue().find(row=>row.id===official.id);
content.batch([{id:official.id,value:'another client',version:updated.version}]);
assert.throws(()=>content.restore(saved.batchId,Object.fromEntries(content.catalogue().map(row=>[row.id,row.version]))),{status:409});
store.close();store=createStudyStore(fixture);content=store.content();
assert.equal(content.catalogue().find(row=>row.id===official.id).value,'another client');
assert.equal(content.catalogue().find(row=>row.id===official.id).original,official.original);
const latest=content.catalogue().find(row=>row.id===official.id);
const currentHTML=readFileSync(path.join(fixture,'web','index.html'),'utf8');
writeFileSync(path.join(fixture,'web','index.html'),currentHTML+'\n<!-- external edit -->');
const exported=content.batch([{id:official.id,value:'pending output',version:latest.version}]);
assert.ok(exported.exportErrors.length);
assert.equal(content.catalogue().find(row=>row.id===official.id).value,'pending output');
assert.ok(readFileSync(path.join(fixture,'web','index.html'),'utf8').includes('external edit'));
store.close();
writeFileSync(path.join(fixture,'web','index.html'),currentHTML);
store=createStudyStore(fixture,{deferExports:true});content=store.content();
const deadline=Date.now()+10000;
while(content.exportState().pending&&!content.exportState().error&&Date.now()<deadline)await new Promise(resolve=>setTimeout(resolve,50));
assert.equal(content.exportState().error,null);
assert.equal(content.exportState().pending,false);
assert.ok(readFileSync(path.join(fixture,'web','index.html'),'utf8').includes('pending output'));
store.close();store=createStudyStore(fixture);content=store.content();
const beforeScriptCount=[...readFileSync(path.join(fixture,'web','index.html'),'utf8').matchAll(/<script\b/g)].length;
const currentRecord=content.catalogue().find(row=>row.id===official.id);
content.batch([{id:official.id,value:'<script>throw Error("unsafe")</script>한글',version:currentRecord.version}]);
const safeHTML=readFileSync(path.join(fixture,'web','index.html'),'utf8');
assert.equal([...safeHTML.matchAll(/<script\b/g)].length,beforeScriptCount);
for(const m of safeHTML.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)){
  if(m[1].includes('application/json'))JSON.parse(m[2]);else new vm.Script(m[2]);
}
assert.ok(safeHTML.includes('\\u003cscript>throw'));
content.captureGoogle(JSON.parse(google.path)[0],google.original,{source:'google-browser',sourceUrl:'https://www.google.com/search?q=fixture',capturedText:google.original,references:[]});
assert.equal(content.documents().googleCaptures.at(-1).capturedText,google.original);
assert.deepEqual(content.documents()['google-source'],metadata);
const compatibilityDB=new DatabaseSync(path.join(fixture,'content','locales.sqlite'));
compatibilityDB.prepare('UPDATE locale_resource SET value = ? WHERE locale = ? AND resource_key = ?').run('CLI fixture translation','ko','feedback.correct');
compatibilityDB.close();
for(const builder of ['scripts/build-locales.mjs','scripts/build-global-editor.mjs']){
  const result=spawnSync(process.execPath,[builder],{cwd:fixture,encoding:'utf8'});
  assert.equal(result.status,0,result.stderr);
}
assert.equal(content.catalogue().find(row=>row.id===locale.id).value,'CLI fixture translation');
content.exportContent();
store.close();
console.log(JSON.stringify({verdict:'PASS',records:catalogue.length,kinds:[...new Set(catalogue.map(row=>row.kind))],atomicBatch:'PASS',conflicts:'PASS',historyRestore:'PASS',originalSource:'PASS',deterministicExport:'PASS',noteOnlyNoHTML:'PASS',externalExportConflict:'PASS',exportRecovery:'PASS',safeOfflineEmbedding:'PASS',fixture}));
